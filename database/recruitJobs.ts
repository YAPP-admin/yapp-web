/** 직군별 인재상 & JD (모집 안내 > 직군 카드 > 자세히 보기) */
export interface RecruitJobTalentItem {
  title: string;
  /** 설명 줄. 항목이 하위 묶음으로 나뉘면 children을 쓴다 */
  lines?: string[];
  /** 화살표(→)와 함께 강조해서 보여 주는 요약 */
  summary?: string;
  children?: { title: string; lines: string[] }[];
}

export interface RecruitJob {
  slug: string;
  name: string;
  description: string;
  /** 직군 카드와 같은 색 구성 */
  backgroundColor: string;
  fontColor: string;
  /** 소개 카드 오른쪽에 놓는 캐릭터 그림 (카드와 같은 색 배경) */
  character: string;
  talent: {
    intro?: string;
    /** 항목 제목 앞에 번호를 붙인다 */
    numbered?: boolean;
    items: RecruitJobTalentItem[];
  };
  jd: { title: string; lines: string[] }[];
}

